def get_current_academic_year(target_date: Optional[date] = None) -> int:
    """
    คำนวณปีการศึกษาปัจจุบันของมหาวิทยาลัยในไทยอัตโนมัติ:
    - ภาคเรียนที่ 1 เปิดช่วงเดือนมิถุนายน (เดือน 6 เป็นต้นไป) นับเป็นปีการศึกษาปัจจุบัน (พ.ศ.)
    - เดือนมกราคม - พฤษภาคม (เดือน 1-5) ยังคงเป็นภาคเรียนที่ 2 ของปีการศึกษาก่อนหน้า
    """
    if target_date is None:
        try:
            target_date = datetime.now(ZoneInfo("Asia/Bangkok")).date()
        except Exception:
            target_date = datetime.now().date()
            
    be_year = target_date.year + 543
    return be_year if target_date.month >= 6 else (be_year - 1)


def calculate_study_year(entry_year_be: int, target_date: Optional[date] = None) -> str:
    """
    คำนวณชั้นปีอัตโนมัติตามปีการศึกษาปัจจุบัน:
    ตัวอย่าง (ปีการศึกษา 2569):
    - รหัส 69 (เข้า 2569) -> ปี 1
    - รหัส 68 (เข้า 2568) -> ปี 2
    - รหัส 67 (เข้า 2567) -> ปี 3
    - รหัส 66 (เข้า 2566) -> ปี 4
    - เข้าก่อน 2566 -> ปี 4+
    เมื่อเวลาผ่านไปขึ้นปี 2570 ระบบจะขยับอัตโนมัติ:
    - รหัส 70 (เข้า 2570) -> ปี 1
    - รหัส 69 (เข้า 2569) -> ปี 2
    - รหัส 68 (เข้า 2568) -> ปี 3
    """
    current_academic_year = get_current_academic_year(target_date)
    diff = current_academic_year - entry_year_be
    year_num = diff + 1

    if year_num <= 0:
        return "ปี 1 (ล่วงหน้า)"
    elif year_num == 1:
        return "ปี 1"
    elif year_num == 2:
        return "ปี 2"
    elif year_num == 3:
        return "ปี 3"
    elif year_num == 4:
        return "ปี 4"
    else:
        return f"ปี {year_num} (เกิน 4 ปี)"


def decode_student_barcode(barcode: str, scan_date: Optional[date] = None) -> Dict[str, Any]:
    """
    ถอดรหัสบาร์โค้ดนักศึกษา เพื่อดึงข้อมูล:
    ชั้นปี, ปีการศึกษา, ระดับหลักสูตร, คณะ, สาขาวิชา
    """
    clean_code = str(barcode).strip()
    
    # รหัสนักศึกษาต้องเป็นตัวเลข 10 หลักเท่านั้น
    if len(clean_code) == 10 and clean_code.isdigit():
        year_prefix = clean_code[0:2]
        degree_code = clean_code[2:3]
        faculty_code = clean_code[3:5]
        major_code = clean_code[5:7]
        section_code = clean_code[7:8]
        seq_code = clean_code[8:10]

        # 1. ปีการศึกษาที่เข้า (เช่น 68 -> 2568)
        entry_year_int = int(f"25{year_prefix}")
        entry_year = str(entry_year_int)

        # 2. คำนวณชั้นปีปัจจุบันอัตโนมัติ (เช่น ปี 1, ปี 2, ปี 3)
        study_year = calculate_study_year(entry_year_int, scan_date)

        # 3. รูปแบบหลักสูตร / ระดับการศึกษา (1 = ภาคปกติ / 2 = กศ.บป. / 3 = ปริญญาโท และ ปริญญาเอก)
        degree_level = DEGREE_LEVELS.get(degree_code, f"รูปแบบรหัส {degree_code}")

        # 4. คณะ และ สาขาวิชา (ตรวจสอบจากรหัสหลักสูตร SSKRU 4 หลัก เช่น 1506, 2732, 0403 ก่อน)
        program_code = clean_code[3:7]
        program_info = SSKRU_PROGRAMS.get(program_code)

        if program_info:
            faculty = program_info["faculty"]
            department = program_info["major"]
        else:
            faculty = FACULTIES.get(faculty_code, f"คณะ (รหัส {faculty_code})")
            department = MAJORS.get(major_code, f"สาขาวิชา (รหัส {major_code})")

        return {
            "student_code": clean_code,
            "entry_year": entry_year,
            "study_year": study_year,
            "degree_level": degree_level,
            "faculty": faculty,
            "department": department,
            "faculty_code": faculty_code,
            "major_code": major_code,
            "section_code": section_code,
            "seq_code": seq_code,
            "is_valid": True,
        }
    else:
        # กรณีรหัสแบบอื่นๆ (สแกนบัตรสั้น หรือบัตรทดสอบ)
        return {
            "student_code": clean_code,
            "entry_year": "ทั่วไป",
            "study_year": "บุคคลทั่วไป",
            "degree_level": "บุคคลทั่วไป/ไม่ระบุ",
            "faculty": "ทั่วไป",
            "department": "ทั่วไป",
            "faculty_code": "-",
            "major_code": "-",
            "section_code": "-",
            "seq_code": "-",
            "is_valid": False,
        }
